package sca

import org.junit.jupiter.api.Tag
import org.junit.jupiter.api.Test
import sca.model.Json
import sca.model.RawComponent
import sca.model.ScanResult
import sca.normalize.Readers
import tools.jackson.module.kotlin.readValue
import java.nio.file.Files
import java.nio.file.Path
import kotlin.io.path.isDirectory
import kotlin.io.path.name

/**
 * Field coverage per tool and for the merged result, over benchmark output dirs (one `sca scan -o` dir each).
 * ./gradlew analysis -Dsca.benchDir=<dir> [-Dsca.labOut=../lab/out]   → docs/analysis/coverage.md
 */
@Tag("analysis")
class Coverage {
    private val fields: List<Pair<String, (RawComponent) -> Boolean>> = listOf(
        "version" to { it.version != null }, "license" to { it.licenses.isNotEmpty() }, "hash" to { it.hashes.isNotEmpty() },
        "downloadUrl" to { it.downloadUrl != null }, "supplier" to { it.supplier != null }, "sourceRepo" to { it.sourceRepo != null },
        "scope" to { it.scope != null }, "location" to { it.locations.isNotEmpty() },
    )

    private fun pct(n: Int, of: Int) = if (of == 0) "–" else "${n * 100 / of}%"

    private fun toolTable(raws: Map<String, Path>): String = buildString {
        appendLine("| tool | components | edges | roots | " + fields.joinToString(" | ") { it.first } + " |")
        appendLine("|---" + "|---".repeat(3 + fields.size) + "|")
        raws.forEach { (tool, file) ->
            val r = runCatching { Readers.read(tool, file) }.getOrNull()
            if (r == null) { appendLine("| $tool | unreadable | | | " + " | ".repeat(fields.size - 1) + " |"); return@forEach }
            val cs = r.components
            appendLine("| $tool | ${cs.size} | ${r.edges.size} | ${r.roots?.size ?: "–"} | " +
                fields.joinToString(" | ") { (_, has) -> pct(cs.count(has), cs.size) } + " |")
        }
    }

    private fun mergedLine(name: String, r: ScanResult): String {
        val cs = r.components
        fun src(f: (sca.model.Component) -> sca.model.Sourced<*>?) =
            cs.mapNotNull { f(it)?.source }.groupingBy { it }.eachCount().entries.sortedByDescending { it.value }.joinToString(" ") { "${it.key}:${it.value}" }
        return "| $name | ${r.status} | ${cs.size} | ${cs.count { it.direct }} | ${cs.count { it.needsReview }} | ${cs.count { it.foundBy.size == 1 }} | " +
            "${pct(cs.count { it.licenses != null }, cs.size)} (${src { it.licenses }}) | ${pct(cs.count { it.downloadUrl != null }, cs.size)} (${src { it.downloadUrl }}) | " +
            "${pct(cs.count { it.supplier != null }, cs.size)} | ${pct(cs.count { it.sourceRepo != null }, cs.size)} | ${pct(cs.count { it.hashes.isNotEmpty() }, cs.size)} | " +
            "${r.warnings.groupingBy { it.code }.eachCount()} |"
    }

    @Test fun report() {
        val bench = Path.of(System.getProperty("sca.benchDir") ?: error("-Dsca.benchDir is required"))
        val runs = Files.list(bench).use { s -> s.filter { it.isDirectory() && Files.exists(it.resolve("raw")) }.sorted().toList() }
        val out = StringBuilder("# Measured field coverage\n\nGenerated by `./gradlew analysis -Dsca.benchDir=…` from `sca scan` output dirs.\n\n")
        out.appendLine("## Merged result per benchmark\n")
        out.appendLine("| benchmark | status | components | direct | needs review | single-tool | license (by source) | download URL (by source) | supplier | source repo | hash | warnings |")
        out.appendLine("|---|---|---|---|---|---|---|---|---|---|---|---|")
        runs.forEach { d -> Files.exists(d.resolve("result.json")).takeIf { it }?.let { out.appendLine(mergedLine(d.name, Json.mapper.readValue(d.resolve("result.json").toFile()))) } }
        out.appendLine("\n## Per tool, before merging\n")
        runs.forEach { d ->
            val raws = listOf("cdxgen", "syft", "trivy", "scancode").associateWith { d.resolve("raw/$it.json") }.filterValues { Files.exists(it) }
            out.appendLine("### ${d.name}\n").appendLine(toolTable(raws))
        }
        System.getProperty("sca.labOut")?.let { lab ->
            val l = Path.of(lab)
            out.appendLine("### lab (npm with package-lock.json, host CLIs)\n").appendLine(toolTable(mapOf(
                "cdxgen" to l.resolve("cdxgen.json"), "syft" to l.resolve("syft-dir.json"), "trivy" to l.resolve("trivy-dir.cdx.json"))))
        }
        Files.writeString(Path.of("../docs/analysis/coverage.md"), out.toString())
        println(out)
    }
}
